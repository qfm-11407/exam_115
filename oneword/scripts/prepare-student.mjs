import {readFile,writeFile} from 'node:fs/promises';
const root=new URL('../',import.meta.url),source=new URL('../public/',import.meta.url);
let html=await readFile(new URL('play.html',source),'utf8');
const css=await readFile(new URL('style.css',source),'utf8');
const canvas=(await readFile(new URL('canvas.js',source),'utf8')).replace('export class InkPad','class InkPad');
const app=await readFile(new URL('app.js',source),'utf8');
const teacherAt=app.indexOf("if (page === 'teacher')"),studentAt=app.indexOf("if (page === 'play')"),screenAt=app.indexOf("if (page === 'screen')");
if(teacherAt<0||studentAt<0||screenAt<0)throw Error('Cannot isolate student controller');
let controller=app.slice(0,teacherAt)+app.slice(studentAt,screenAt);
controller=controller.replace("import { InkPad } from './canvas.js';",'');
const apiAt=controller.indexOf('async function api('),connectionAt=controller.indexOf('function connection(',apiAt);
if(apiAt<0||connectionAt<0)throw Error('Cannot locate student transport');
const transport=await readFile(new URL('native-transport.js',import.meta.url),'utf8');
controller=controller.slice(0,apiAt)+transport+'\n'+controller.slice(connectionAt);
controller=controller.replace("const params = new URLSearchParams(location.search), code = params.get('room')?.toUpperCase() || '';","const code=String(boot.room||'').toUpperCase();");
controller=controller.replace(/history\.replaceState\(null, '', [^\n;]+\);/g,'');
controller=controller.replaceAll('word-arena-player:','oneword:direct:player:').replaceAll('word-arena-draft:','oneword:direct:draft:').replaceAll('word-arena-claim:','oneword:direct:claim:').replaceAll('word-arena-pending:','oneword:direct:pending:');
controller=controller.replace("submitted = true; toast('已交卷，等待統一揭曉');","submitted = true; toast('圖片已保存，等待統一揭曉');");
html=html.replace('<link rel="stylesheet" href="/style.css">','<style>'+css+'</style>').replace('<script type="module" src="/app.js"></script>','');
html=html.replace('<a class="brand" href="/">','<span class="brand">').replace('</small></span></a>','</small></span></span>');
html=html.replace('<p id="join-status"','<p class="muted">平板模式 v2.12.0</p><p id="join-status"');
const script='const boot = <?!= boot ?>;\n'+canvas+'\n'+controller;
if(/<\/script/i.test(script))throw Error('Unexpected embedded script delimiter');
html=html.replace('</body>','<script>'+script+'</script></body>');
await writeFile(new URL('gas/Student.html',root),'<!-- Generated by scripts/prepare-student.mjs from public student sources. -->\n'+html);
console.log('Prepared gas/Student.html: direct google.script.run transport; no nested GitHub bridge.');
